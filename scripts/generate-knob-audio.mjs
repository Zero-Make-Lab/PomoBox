import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

// The demo's decaying noise, band-pass Q and click lengths, made reproducible.
// Run with Node; no packages or audio tools are required.
const rate=24000,q=.75;
function clip(name,durationMs,frequency,seed){
  const count=rate*durationMs/1000,w=2*Math.PI*frequency/rate,alpha=Math.sin(w)/(2*q),a0=1+alpha;
  const b0=alpha/a0,b2=-alpha/a0,a1=-2*Math.cos(w)/a0,a2=(1-alpha)/a0;
  let x1=0,x2=0,y1=0,y2=0,state=seed;const values=[];
  for(let i=0;i<count;i++){
    state^=state<<13;state^=state>>>17;state^=state<<5;
    const x=((state>>>0)/4294967296*2-1)*Math.exp(-i/count*8);
    const y=b0*x+b2*x2-a1*y1-a2*y2;values.push(y);x2=x1;x1=x;y2=y1;y1=y;
  }
  const peak=Math.max(...values.map(Math.abs));
  const pcm=values.map(v=>Math.round(v/peak*127));
  const rows=[];for(let i=0;i<pcm.length;i+=24)rows.push('  '+pcm.slice(i,i+24).join(', '));
  return `static const int8_t KNOB_${name}_PCM[] PROGMEM = {\n${rows.join(',\n')}\n};\nstatic constexpr float KNOB_${name}_DEMO_GAIN = ${(peak*.24).toFixed(9)}f;\n`;
}
const header='#pragma once\n#include <Arduino.h>\n\n// Generated by scripts/generate-knob-audio.mjs. Signed 8-bit mono PCM.\nstatic constexpr uint32_t KNOB_SAMPLE_RATE = 24000;\n\n'+clip('TURN',27,1800,0x504f4d4f)+'\n'+clip('PRESS',45,850,0x424f584b);
await writeFile(fileURLToPath(new URL('../include/knob_samples.h',import.meta.url)),header);
console.log('Generated shared 27ms turn and 45ms press/release samples.');
